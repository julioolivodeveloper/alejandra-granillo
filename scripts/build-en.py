def main():
    s = open(os.path.join(ROOT, 'index.html'), encoding='utf-8').read()

    for es, en, n in LITERAL:
        assert s.count(es) == n, f'expected {n}x: {es[:70]!r} (found {s.count(es)})'
        s = s.replace(es, en)

    def swap(attr, key, value):
        nonlocal s
        pat = re.compile(r'(<(\w+)\b[^>]*\s' + attr + r'="' + key + r'"[^>]*>)(.*?)(</\2>)', re.S)
        s, n = pat.subn(lambda m: m.group(1) + value + m.group(4), s)
        assert n, f'{attr}="{key}" not found in index.html'

    for key, value in TEXT.items():
        swap('data-t', key, html.escape(value, quote=False))
    for key, value in HTML.items():
        swap('data-t-html', key, value)

    used = set(re.findall(r'data-t(?:-html)?="(\w+)"', s))
    missing = used - set(TEXT) - set(HTML)
    assert not missing, f'no English for: {sorted(missing)}'

    os.makedirs(os.path.join(ROOT, 'en'), exist_ok=True)
    with open(os.path.join(ROOT, 'en', 'index.html'), 'w', encoding='utf-8') as f:
        f.write(s)
    print('wrote en/index.html', len(s.encode()), 'bytes')


if __name__ == '__main__':
    main()
